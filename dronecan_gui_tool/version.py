__version__ = 1, 2, 28

# __version__ above is the last release; update it as part of the release process, as before. The full version is
# derived from the git release tags ([v]X.Y.Z). It gives the last release, the number of commits after it, the last
# commit, and whether there are uncommitted changes:
#   1.2.28                          on release v1.2.28
#   1.2.28.post50+ge41a19c          50 commits after release v1.2.28, the last commit being e41a19c
#   1.2.28.post50+ge41a19c.dirty    as above, with uncommitted changes
#   1.2.28+unknown                  __version__ above, when the git information is not available
#
# The information comes from the first of these that is available:
#   1. git, when running from a git checkout (including editable installs)
#   2. _version.py, which setup.py generates when the package is built, for installed and frozen packages
#   3. .git_archival.txt, which GitHub fills in when an archive of the repository is downloaded
#   4. __version__ above, e.g. in a shallow clone without tags
#

import os
import re
import subprocess
import sys

_RELEASE = '.'.join(map(str, __version__))

_PACKAGE_DIR = os.path.dirname(os.path.abspath(__file__))
_SOURCE_DIR = os.path.dirname(_PACKAGE_DIR)

# git describe output: <tag>-<number of commits after it>-g<commit>[-dirty]
_DESCRIBE_PATTERN = re.compile(r'v?(\d+(?:\.\d+)*)-(\d+)-g([0-9a-f]+)(-dirty)?')


def _from_git():
    # Frozen executables must never consult git: the current directory may be some unrelated repository.
    # The .git check also rejects installs into a venv that happens to live inside a checkout.
    if getattr(sys, 'frozen', False) or not os.path.exists(os.path.join(_SOURCE_DIR, '.git')):
        return None
    try:
        out = subprocess.run(['git', 'describe', '--tags', '--long', '--dirty', '--match', '*[0-9]*'],
                             cwd=_SOURCE_DIR, capture_output=True, text=True, timeout=5, check=True,
                             creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0)).stdout
    except Exception:
        return None
    m = _DESCRIBE_PATTERN.fullmatch(out.strip())
    if not m:
        return None
    return m.group(1), int(m.group(2)), m.group(3), bool(m.group(4))


def _from_generated():
    try:
        from . import _version
        return _version.release, _version.distance, _version.commit, _version.dirty
    except (ImportError, AttributeError):    # AttributeError: written by something else, e.g. setuptools-scm
        return None


def _from_archival():
    try:
        with open(os.path.join(_SOURCE_DIR, '.git_archival.txt')) as f:
            fields = dict(line.split(':', 1) for line in f if ':' in line)
    except OSError:
        return None
    describe = fields.get('describe-name', '').strip()
    node = fields.get('node', '').strip()
    if '$Format' in describe:
        return None     # Not an archive: the placeholders are only filled in when GitHub creates one
    m = _DESCRIBE_PATTERN.fullmatch(describe)
    if m:
        return m.group(1), int(m.group(2)), m.group(3), False
    # Exactly on a release tag, the archive gives just the tag
    m = re.fullmatch(r'v?(\d+(?:\.\d+)*)', describe)
    if m and re.fullmatch(r'[0-9a-f]{7,}', node):
        return m.group(1), 0, node[:7], False
    return None


def format_version(release, distance, commit, dirty):
    if commit is None:
        return release + '+unknown'     # The git information is not available
    if distance == 0 and not dirty:
        return release
    version = '%s.post%d+g%s' % (release, distance, commit) if distance else '%s+g%s' % (release, commit)
    return version + '.dirty' if dirty else version


def generated_module_source():
    """The contents of _version.py, which setup.py writes into the package when it is built."""
    return ('# Generated by setup.py from the git history; do not edit.\n'
            'release = %r\ndistance = %r\ncommit = %r\ndirty = %r\n' % _VERSION_INFO)


_VERSION_INFO = _from_git() or _from_generated() or _from_archival() or (_RELEASE, None, None, False)

# e.g. '1.2.28.post50+ge41a19c.dirty'
__version_string__ = format_version(*_VERSION_INFO)

# Numeric release tuple (major, minor, patch), e.g. for the DroneCAN node software_version field
__version__ = tuple(int(x) for x in _VERSION_INFO[0].split('.'))
